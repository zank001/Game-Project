/* Register events/chapters/endings. Content files call: Q.add([ {...}, {...} ]) */
Q.add = function (list) {
  if (!Array.isArray(list)) list = [list];
  list.forEach(function (e) {
    if (!e || !e.id) { Q.dups.push('(event without id)'); return; }
    if (Q._byId[e.id]) { Q.dups.push(e.id); return; }
    Q._byId[e.id] = e;
    Q.events.push(e);
  });
};

